NEXT = {"S": "T", "T": "A", "A": "R"}


def cases() -> list[dict]:
    rows = []
    for slot, nxt in NEXT.items():
        earlier = [s for s in ("S", "T") if ("STAR".index(s) < "STAR".index(slot))]
        for kind, answers in (("thin", THIN[slot]), ("rich", RICH[slot])):
            for i, answer in enumerate(answers):
                rows.append({
                    "id": f"{slot}-{kind}-{i + 1}",
                    "slot": slot,
                    "next": nxt,
                    "answer": answer,
                    "gold": slot if kind == "thin" else nxt,
                    "earlier": [{"slot": s, "answer": STORY[s]} for s in earlier],
                })
    return rows
